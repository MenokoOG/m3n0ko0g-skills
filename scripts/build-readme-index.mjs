/* build-readme-index.mjs: regenerate the skill index in README.md from the
   skills themselves.

   The index sits between the two marker comments. Audit-pass skills come
   first in run order (read from AUDIT_ORDER in mcp/server.mjs, the one place
   that order lives), then the rest alphabetically.

   Usage:
     node scripts/build-readme-index.mjs            # rewrite the block
     node scripts/build-readme-index.mjs --check    # exit 1 if README is stale */

import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { parseSkill, firstSentence } from "./skill-model.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const README = join(ROOT, "README.md");
const START = "<!-- skills-index:start (generated by scripts/build-readme-index.mjs, do not edit) -->";
const END = "<!-- skills-index:end -->";

export function auditOrder(serverSource) {
  const m = /const AUDIT_ORDER = \[([^\]]*)\]/.exec(serverSource);
  if (!m) throw new Error("AUDIT_ORDER not found in mcp/server.mjs");
  return [...m[1].matchAll(/"([^"]+)"/g)].map((x) => x[1]);
}

export function renderIndex(skills, order) {
  const rank = (name) => (order.includes(name) ? order.indexOf(name) : Infinity);
  const sorted = [...skills].sort((a, b) => rank(a.name) - rank(b.name) || a.name.localeCompare(b.name));
  const rows = sorted.map((s) => {
    const track = order.includes(s.name) ? `audit ${order.indexOf(s.name) + 1}` : "general";
    return `| [${s.name}](skills/${s.name}.SKILL.md) | ${track} | ${s.version} | ${firstSentence(s.description)} |`;
  });
  return ["| Skill | Track | Version | What it does |", "|---|---|---|---|", ...rows].join("\n");
}

export function replaceBlock(readme, block) {
  const a = readme.indexOf(START);
  const b = readme.indexOf(END);
  if (a === -1 || b === -1 || b < a) throw new Error("skills-index markers not found in README.md");
  return readme.slice(0, a + START.length) + "\n" + block + "\n" + readme.slice(b);
}

function main() {
  const dir = join(ROOT, "skills");
  const skills = readdirSync(dir)
    .filter((f) => f.endsWith(".SKILL.md"))
    .sort()
    .map((f) => parseSkill(readFileSync(join(dir, f), "utf8")).meta);
  const order = auditOrder(readFileSync(join(ROOT, "mcp", "server.mjs"), "utf8"));

  const current = readFileSync(README, "utf8").replace(/\r\n/g, "\n");
  const next = replaceBlock(current, renderIndex(skills, order));

  if (process.argv.includes("--check")) {
    if (next !== current) {
      console.error('README skill index is stale, run "npm run build:index"');
      process.exit(1);
    }
    console.log(`README index current (${skills.length})`);
  } else {
    writeFileSync(README, next);
    console.log(`README index written (${skills.length})`);
  }
}

if (process.argv[1] && import.meta.url.endsWith(process.argv[1].split(/[\\/]/).pop())) main();
